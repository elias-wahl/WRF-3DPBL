#!/usr/bin/env python3
"""Which cited papers are on disk, and where.

Layout (concept/sources/, outside git):
  papers/<bibkey> - <Author> - <Year> - <Title>.pdf   one file per bib key (both bib files)
  papers/variants/<bibkey> - ...                      second copies that differ from the main one
  papers/notes.tsv                                    hand-kept "key<TAB>note" (partial copy, abstract only, ...)
  papers/INDEX.md                                     written by `status --write`
  unkeyed/                                            papers on disk without a bib entry
  own_and_project/                                    theses, proposals, posters, the expose
  zotero_storage/ + storage.zip                       Zotero export (PDFs moved to papers/; zip = original)

Usage:
  sources_index.py status [--write]        coverage per document, missing keys with doi.org links
  sources_index.py adopt <file> <key>      move a downloaded PDF to papers/ under its key
  sources_index.py path <key>              print the file of a key (for scripts: pdftotext "$(... path k)")
"""
import argparse, glob, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
CONCEPT = os.path.dirname(HERE)
PAPERS = os.path.join(CONCEPT, "sources", "papers")
DOCS = {  # document -> (tex files, bib files it loads)
    "phd_concept": (["phd_concept/0*.tex", "phd_concept/A*.tex", "phd_concept/figures/*.tex"],
                    ["phd_concept/references.bib"]),
    "pbl_assumptions": (["pbl_assumptions/*.tex", "pbl_assumptions_table.tex"],
                        ["phd_concept/references.bib", "pbl_assumptions/extra.bib"]),
}
CITE = re.compile(r"\\(?:[a-zA-Z]*cite[a-zA-Z]*|nocite)\*?(?:\[[^\]]*\]){0,2}\{([^}]*)\}")


def cited_keys(patterns):
    keys = set()
    for pat in patterns:
        for f in glob.glob(os.path.join(CONCEPT, pat)):
            s = re.sub(r"(?<!\\)%.*", "", open(f, encoding="utf-8").read())
            for m in CITE.finditer(s):
                keys |= {k.strip() for k in m.group(1).split(",") if k.strip()}
    return keys


def read_bib(path):
    bib, out = open(os.path.join(CONCEPT, path), encoding="utf-8").read(), {}
    for m in re.finditer(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", bib):
        i, depth = m.end(), 1
        while depth and i < len(bib):
            depth += (bib[i] == "{") - (bib[i] == "}")
            i += 1
        body, f = bib[m.end():i - 1], {"type": m.group(1).lower()}
        for fm in re.finditer(r"(\w+)\s*=\s*\{((?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*)\}", body):
            f[fm.group(1).lower()] = re.sub(r"\s+", " ", fm.group(2))
        out[m.group(2)] = f
    return out


def files_by_key():
    out = {}
    for p in sorted(glob.glob(os.path.join(PAPERS, "* - *"))):
        out.setdefault(os.path.basename(p).split(" - ", 1)[0], []).append(p)
    return out


def notes():
    p = os.path.join(PAPERS, "notes.tsv")
    if not os.path.exists(p):
        return {}
    return dict(l.rstrip("\n").split("\t", 1) for l in open(p, encoding="utf-8")
                if "\t" in l and not l.startswith("#"))


def pages(p):
    try:
        r = subprocess.run(["pdfinfo", p], capture_output=True, text=True, timeout=20)
        return re.search(r"Pages:\s+(\d+)", r.stdout).group(1)
    except Exception:
        return "?"


def short(f):
    au = f.get("author", "").split(" and ")[0].split(",")[0].strip("{}")
    return f"{au} {f.get('year', '')}: {f.get('title', '')[:80]}".replace("{", "").replace("}", "")


def status(write):
    have, nt = files_by_key(), notes()
    rows, lines = {}, []
    for doc, (tex, bibfs) in DOCS.items():
        bib, cited = {k: v for b in bibfs for k, v in read_bib(b).items()}, cited_keys(tex)
        miss = sorted(k for k in cited if k not in have)
        print(f"{doc}: {len(cited)} cited, {len(cited) - len(miss)} on disk, {len(miss)} missing")
        for k in miss:
            f = bib.get(k, {})
            link = f"https://doi.org/{f['doi']}" if f.get("doi") else "(no DOI)"
            print(f"  {k:20s} {link:55s} {short(f)[:70]}" + (f"  [{nt[k]}]" if k in nt else ""))
        for k, f in bib.items():
            rows.setdefault(k, [f, set()])[1].update({doc} if k in cited else set())
    if not write:
        return
    lines += ["# Papers on disk, by bib key", "",
              "Generated by `concept/scripts/sources_index.py status --write` — do not edit; notes go in `notes.tsv`.",
              "`cited in`: which document cites the key (empty = in the bib, not cited).", "",
              "| key | cited in | pages | reference | file / note |", "|---|---|---|---|---|"]
    for k in sorted(rows):
        f, docs = rows[k]
        fs = have.get(k, [])
        cell = f"`{os.path.basename(fs[0])}`" if fs else "**missing**" + (
            f" <https://doi.org/{f['doi']}>" if f.get("doi") else "")
        if k in nt:
            cell += f" — {nt[k]}"
        lines.append(f"| {k} | {', '.join(sorted(docs))} | {pages(fs[0]) if fs else ''} | "
                     f"{short(f).replace('|', '/')} | {cell} |")
    extra = sorted(set(have) - set(rows))
    if extra:
        lines += ["", "Files whose key is in neither bib: " + ", ".join(extra)]
    open(os.path.join(PAPERS, "INDEX.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", os.path.join(PAPERS, "INDEX.md"))


def adopt(src, key):
    if files_by_key().get(key):
        sys.exit(f"{key} already has {files_by_key()[key][0]}; move the old one to variants/ first")
    with open(src, "rb") as fh:
        if fh.read(4) != b"%PDF":
            sys.exit(f"{src} is not a PDF")
    dest = os.path.join(PAPERS, f"{key} - {os.path.basename(src)}")
    shutil.move(src, dest)
    print(dest)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("status"); s.add_argument("--write", action="store_true")
    a = sp.add_parser("adopt"); a.add_argument("file"); a.add_argument("key")
    p = sp.add_parser("path"); p.add_argument("key")
    args = ap.parse_args()
    if args.cmd == "status":
        status(args.write)
    elif args.cmd == "adopt":
        adopt(args.file, args.key)
    else:
        fs = files_by_key().get(args.key)
        if not fs:
            sys.exit(f"{args.key}: no file in {PAPERS}")
        print(fs[0])


if __name__ == "__main__":
    main()
